"""Video tours: a short silent film for a published listing, made only from its own photos.
The listing's agent turns it on from the dashboard; it is off by default.

Nothing is generated by a model. Each real photo gets slow camera movement and a fade to the
next, so the film cannot show a building, room or condition that the photos do not show.

Rendering takes minutes on a small server, so it never happens during a request. A background
thread (start_worker) or `python -m scripts.render_videos` picks up any listing with video turned
on whose video is missing or was made from a different set of photos. Finished videos are stored in the
database, as photos are; UPLOAD_DIR is only a cache.
"""
import hashlib
import io
import os
import subprocess
import tempfile
import threading
import uuid
from pathlib import Path

import imageio_ffmpeg
from PIL import Image, ImageFilter, ImageOps

from . import config, db, images

WIDTH, HEIGHT = 960, 540
FPS = 24
SECONDS_PER_PHOTO = 3.5
FADE_SECONDS = 0.6
ZOOM = 0.12
MIN_PHOTOS = 2  # one photo already shows everything a film of it would
MAX_ATTEMPTS = 3  # for one set of photos; new photos start again
LEASE_MINUTES = 45  # a render older than this died with its server
RENDER_TIMEOUT_SECONDS = 30 * 60
POLL_SECONDS = 60

# Each motion is (zoom, x, y) for ffmpeg's zoompan filter; PROGRESS runs from 0 to 1 over the clip.
_CENTRE = ("iw/2-(iw/zoom/2)", "ih/2-(ih/zoom/2)")
_MOTIONS = [
    (f"1+{ZOOM}*PROGRESS", *_CENTRE),                                # push in
    (f"{1 + ZOOM}", "(iw-iw/zoom)*PROGRESS", _CENTRE[1]),            # pan right
    (f"{1 + ZOOM}-{ZOOM}*PROGRESS", *_CENTRE),                       # pull out
    (f"{1 + ZOOM}", "(iw-iw/zoom)*(1-PROGRESS)", _CENTRE[1]),        # pan left
]


class VideoError(RuntimeError):
    pass


def duration_seconds(photo_count: int) -> float:
    return photo_count * SECONDS_PER_PHOTO - (photo_count - 1) * FADE_SECONDS


def _canvas(photo: bytes) -> Image.Image:
    """A 16:9 frame at twice the film's size, so slow movement does not judder. A photo close to
    16:9 fills it; a portrait photo stays whole over a blurred copy of itself, because cropping
    it would hide most of the building."""
    size = (WIDTH * 2, HEIGHT * 2)
    with Image.open(io.BytesIO(photo)) as img:
        img = img.convert("RGB")
        if abs(img.width / img.height - WIDTH / HEIGHT) < 0.45:
            return ImageOps.fit(img, size, Image.Resampling.LANCZOS)
        back = ImageOps.fit(img, size, Image.Resampling.BILINEAR).filter(ImageFilter.GaussianBlur(40))
        front = ImageOps.contain(img, size, Image.Resampling.LANCZOS)
        back.paste(front, ((size[0] - front.width) // 2, (size[1] - front.height) // 2))
        return back


def _filter_graph(photo_count: int) -> tuple[str, str]:
    """The ffmpeg filter graph, and the name of its final output."""
    frames = round(SECONDS_PER_PHOTO * FPS)
    parts = []
    for i in range(photo_count):
        zoom, x, y = (expr.replace("PROGRESS", f"(on/{frames - 1})") for expr in _MOTIONS[i % len(_MOTIONS)])
        parts.append(f"[{i}:v]zoompan=z='{zoom}':x='{x}':y='{y}':d={frames}:s={WIDTH}x{HEIGHT}:fps={FPS},"
                     f"setsar=1,format=yuv420p[p{i}]")
    last = "p0"
    for i in range(1, photo_count):
        offset = i * (SECONDS_PER_PHOTO - FADE_SECONDS)
        parts.append(f"[{last}][p{i}]xfade=transition=fade:duration={FADE_SECONDS}:offset={offset:.3f}[x{i}]")
        last = f"x{i}"
    return ";".join(parts), last


def render(photos: list[bytes]) -> bytes:
    """Return the MP4 for these photos, in the order given."""
    if len(photos) < MIN_PHOTOS:
        raise VideoError(f"A video needs at least {MIN_PHOTOS} photos.")
    with tempfile.TemporaryDirectory(prefix="listing-video-") as tmp:
        tmp = Path(tmp)
        inputs: list[str] = []
        for i, photo in enumerate(photos):
            path = tmp / f"{i}.jpg"
            _canvas(photo).save(path, "JPEG", quality=88)
            inputs += ["-i", str(path)]
        graph, last = _filter_graph(len(photos))
        out = tmp / "tour.mp4"
        cmd = ["nice", "-n", "19", imageio_ffmpeg.get_ffmpeg_exe(), "-hide_banner", "-loglevel", "error", "-y",
               "-filter_threads", "1", "-filter_complex_threads", "1", *inputs,
               "-filter_complex", graph, "-map", f"[{last}]", "-an",
               "-c:v", "libx264", "-preset", "veryfast", "-crf", "26", "-profile:v", "main",
               "-pix_fmt", "yuv420p", "-threads", "1", "-movflags", "+faststart", str(out)]
        try:
            subprocess.run(cmd, check=True, capture_output=True, text=True, timeout=RENDER_TIMEOUT_SECONDS)
        except subprocess.CalledProcessError as exc:
            raise VideoError((exc.stderr or "ffmpeg failed").strip()[-500:]) from exc
        except subprocess.TimeoutExpired as exc:
            raise VideoError(f"ffmpeg took longer than {RENDER_TIMEOUT_SECONDS} seconds") from exc
        return out.read_bytes()


def photos_key(names: list[str]) -> str:
    """Identifies an ordered set of photos, so a new cover or photo set triggers a new video."""
    return hashlib.sha256("\n".join(names).encode()).hexdigest()[:32]


CANDIDATES = """
SELECT l.listing_id,
       array_agg(i.file_name ORDER BY (i.position = l.cover_position) DESC, i.position) AS names,
       v.photos_key AS done_key, v.status, v.attempts, v.started_at > now() - make_interval(mins => %s) AS leased
FROM listings l
JOIN listing_images i USING (listing_id)
LEFT JOIN listing_videos v USING (listing_id)
WHERE l.status = 'published' AND l.video_enabled
  AND NOT EXISTS (SELECT 1 FROM outcomes o WHERE o.listing_id = l.listing_id)
GROUP BY l.listing_id, l.cover_position, v.photos_key, v.status, v.attempts, v.started_at
HAVING count(*) >= %s
ORDER BY l.listing_id"""

CLAIM = """
INSERT INTO listing_videos (listing_id, photos_key, status, attempts, started_at)
VALUES (%(id)s, %(key)s, 'rendering', 1, now())
ON CONFLICT (listing_id) DO UPDATE
SET status = 'rendering', started_at = now(), error = NULL, photos_key = EXCLUDED.photos_key,
    attempts = CASE WHEN listing_videos.photos_key = EXCLUDED.photos_key THEN listing_videos.attempts + 1 ELSE 1 END
WHERE listing_videos.status <> 'rendering' OR listing_videos.photos_key <> EXCLUDED.photos_key
   OR listing_videos.started_at <= now() - make_interval(mins => %(lease)s)
RETURNING listing_id"""


def _needs_work(row: dict) -> bool:
    if row["done_key"] != photos_key(row["names"]):
        return True  # no video yet, or the photos changed
    if row["status"] == "ready" or row["attempts"] >= MAX_ATTEMPTS:
        return False
    return not (row["status"] == "rendering" and row["leased"])


def pending(conn) -> list[dict]:
    rows = conn.execute(CANDIDATES, [LEASE_MINUTES, MIN_PHOTOS]).fetchall()
    return [r for r in rows if _needs_work(r)]


def render_next() -> bool:
    """Render one listing's video. Returns False when nothing is waiting. No database
    connection stays open during the render, which can take minutes."""
    with db.connect() as conn:
        job = None
        for row in pending(conn):
            key = photos_key(row["names"])
            if conn.execute(CLAIM, {"id": row["listing_id"], "key": key, "lease": LEASE_MINUTES}).fetchone():
                job = row
                break
        if job is None:
            return False
        photos = [p for p in (images.load(name, conn) for name in job["names"]) if p]
    listing_id, key = job["listing_id"], photos_key(job["names"])
    try:
        data = render(photos)
    except Exception as exc:  # ffmpeg, an unreadable photo: record it and carry on with other listings
        print(f"video failed for listing {listing_id}: {exc}", flush=True)
        with db.connect() as conn:
            conn.execute("UPDATE listing_videos SET status = 'failed', error = %s "
                         "WHERE listing_id = %s AND photos_key = %s", [str(exc)[:1000], listing_id, key])
        return True
    name = f"{uuid.uuid4().hex}.mp4"
    with db.connect() as conn:
        # The photos may have changed during the render: then this film is out of date and is dropped.
        conn.execute("UPDATE listing_videos SET status = 'ready', file_name = %s, data = %s, photo_count = %s, "
                     "seconds = %s, finished_at = now() WHERE listing_id = %s AND photos_key = %s",
                     [name, data, len(photos), duration_seconds(len(photos)), listing_id, key])
    print(f"video ready for listing {listing_id}: {len(photos)} photos, {len(data)} bytes", flush=True)
    return True


def cached_path(name: str, conn) -> Path | None:
    """The video on disk, restored from the database if the disk was wiped."""
    path = config.UPLOAD_DIR / name
    if path.exists():
        return path
    row = conn.execute("SELECT data FROM listing_videos WHERE file_name = %s", [name]).fetchone()
    if not row or row["data"] is None:
        return None
    config.UPLOAD_DIR.mkdir(parents=True, exist_ok=True)
    temp = config.UPLOAD_DIR / f".{uuid.uuid4().hex}.tmp"
    temp.write_bytes(bytes(row["data"]))
    os.replace(temp, path)  # atomic, so a second request never reads half a file
    return path


def _worker(stop: threading.Event) -> None:
    while not stop.wait(POLL_SECONDS):
        try:
            while not stop.is_set() and render_next():
                pass
        except Exception as exc:  # the database is away, say; try again at the next poll
            print(f"video worker: {exc}", flush=True)


def start_worker() -> threading.Event:
    """Start the background renderer. Set the returned event to stop it."""
    stop = threading.Event()
    threading.Thread(target=_worker, args=(stop,), name="video-worker", daemon=True).start()
    return stop
